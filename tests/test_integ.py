# Integration tests for dashing
#
# Some tests are explicitly checking for broken outputs in order to spot unexpected changes
#
# debdeps: python3-pexpect python3-pyte python3-pytest

from __future__ import unicode_literals

import sys

import pyte
import pytest
import pexpect


def run(w, h, path):
    """Run a pyte virtual terminal"""
    screen = pyte.Screen(w, h)
    stream = pyte.ByteStream(screen)
    env = dict(PYTHONPATH=".", TERM="xterm-256color")
    # Run with the same interpreter as pytest, not the one in the shebang
    child = pexpect.spawn(sys.executable, [path], env=env, dimensions=(h, w))
    child.expect(pexpect.EOF)
    stream.feed(child.before)
    out = screen.display
    child.terminate()
    return out


def check(raw_out, exp):
    """Check expected output"""
    exp = [x.rstrip() for x in exp.splitlines()]
    out = [x.rstrip() for x in raw_out]
    len_ok = len(out) == len(exp)

    if exp == out:
        return

    print("-- out --")
    print("\n".join(out))
    print("-- end out --")
    print("-- diff --")
    for e, o in zip(exp, out):
        m = "*" if e != o else " "
        print(m, "Exp", repr(e))
        print(m, "out", repr(o))

    print("-- end diff --")

    assert len_ok, f"Number of lines in output: {len(out)} != expected: {len(exp)}"
    pytest.fail("Fail")


